describe('Student workspace',() => {
  it('persists the academic workflow and fits supported viewport widths',() => {
    const email = 'student-' + Date.now() + '@example.com'
    const password = 'test-password-123'
    const today = new Date().toISOString().slice(0,10)
    cy.intercept('https://identitytoolkit.googleapis.com/**',{ forceNetworkError:true })
    cy.intercept('POST','http://127.0.0.1:9099/**/accounts:signUp*').as('emulatorSignup')
    cy.visit('/register')
    cy.contains('label','Full name').find('input').type('Taylor Jordan')
    cy.contains('label','Email').find('input').type(email)
    cy.get('input[autocomplete="new-password"]').eq(0).type(password)
    cy.get('input[autocomplete="new-password"]').eq(1).type(password)
    cy.contains('button','Create your account').click()
    cy.wait('@emulatorSignup').its('response.statusCode').should('eq',200)
    cy.location('pathname').should('eq','/app')
    cy.contains('button','Sign out').click()
    cy.contains('label','Email').find('input').type(email)
    cy.contains('label','Password').find('input').type(password)
    cy.contains('button','Sign in').click()
    cy.contains('h1','Taylor')
    cy.contains('nav a','My Courses').click()
    cy.contains('button','Add semester').click()
    cy.get('[name=name]').type('Fall Semester')
    cy.get('[name=start]').type('2026-09-01')
    cy.get('[name=end]').type('2026-12-21')
    cy.contains('button','Save changes').click()
    cy.contains('strong','Fall Semester')
    cy.contains('button','Add course').click()
    cy.get('[name=name]').type('Database Management')
    cy.get('[name=code]').type('COMP214')
    cy.contains('button','Save changes').click()
    cy.contains('h3','Database Management')
    cy.contains('nav a','Assignments').click()
    cy.contains('button','Add assignment').click()
    cy.get('[name=title]').type('Database Project')
    cy.get('[name=course]').select(1)
    cy.get('[name=dueAt]').type('2027-01-15T14:00')
    cy.contains('button','Save changes').click()
    cy.contains('button','Database Project').click()
    cy.get('[name=title]').clear().type('Database Capstone')
    cy.contains('button','Save changes').click()
    cy.contains('button','Database Capstone')
    cy.get('select[aria-label="Status for Database Capstone"]').select('completed')
    cy.get('select[aria-label="Status for Database Capstone"]').should('have.value','completed')
    cy.contains('nav a','Grades').click()
    cy.contains('button','Add assessment').click()
    cy.get('[name=name]').type('Midterm')
    cy.get('[name=weight]').type('70')
    cy.get('[name=earned]').type('82')
    cy.get('[name=completed]').check()
    cy.contains('button','Save changes').click()
    cy.contains('82.0%')
    cy.contains('p','Required average on remaining work: 92.0%')
    cy.contains('nav a','Calendar').click()
    cy.contains('button','Add event').click()
    cy.get('[name=title]').type('Review session')
    cy.get('[name=start]').type(today+'T09:00')
    cy.get('[name=end]').type(today+'T10:00')
    cy.contains('button','Save changes').click()
    cy.get('dialog').should('not.exist')
    cy.contains('.fc-event','Review session').should('be.visible')
    cy.contains('nav a','Settings').click()
    cy.get('[name=focus]').clear().type('1')
    cy.contains('button','Save preferences').click()
    cy.contains('Changes saved.')
    cy.contains('nav a','Focus Mode').click()
    cy.contains('[role=timer]','01:00')
    cy.clock(Date.now()-65000,['Date','setInterval','clearInterval'])
    cy.contains('button',/^Start$/).click()
    cy.tick(60000)
    cy.contains('Study session saved.')
    cy.contains('nav a','Dashboard').click()
    cy.contains('1 completed')
    cy.viewport(1440,900)
    cy.scrollTo('top',{ ensureScrollable:false })
    cy.document().its('documentElement.scrollWidth').should('be.lte',1440)
    cy.screenshot('dashboard',{ capture:'viewport' })
    cy.contains('nav a','Analytics').click()
    cy.contains('Completion rate')
    cy.contains('100%')
    for (const width of [375,768,1024,1440]) {
      cy.viewport(width,900)
      cy.document().its('documentElement.scrollWidth').should('be.lte',width)
      cy.contains('nav a','Calendar').click()
      cy.get('.fc-toolbar-title').should('be.visible')
      if (width === 1440) {
        cy.scrollTo('top',{ ensureScrollable:false })
        cy.screenshot('calendar',{ capture:'viewport' })
      }
      cy.document().its('documentElement.scrollWidth').should('be.lte',width)
      cy.contains('nav a','Analytics').click()
    }
    cy.contains('button','Sign out').click()
    cy.contains('label','Email').find('input').type(email)
    cy.contains('label','Password').find('input').type(password)
    cy.contains('button','Sign in').click()
    cy.contains('nav a','Assignments').click()
    cy.contains('button','Database Capstone')
  })
})





